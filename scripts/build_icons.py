"""Build static/js/icons.js: the Lucide icons this site uses, plus a tiny createIcons().

The full Lucide bundle is ~350 KB for ~1,500 icons; the site uses a couple of
hundred. Icon names live in templates, JS and Python constants (choice lists,
event kinds, nav maps), so this scans every quoted string in those files and
keeps the ones that are Lucide icon names. Over-including is harmless; missing
one shows a console warning and an empty gap where the icon should be.

Usage (re-run after using a new icon name anywhere):
    npm pack lucide@0.469.0 && tar xzf lucide-0.469.0.tgz
    python scripts/build_icons.py package/dist/umd/lucide.js
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / 'static' / 'js' / 'icons.js'
SOURCES = [
    *(ROOT / 'templates').rglob('*.html'),
    *(p for p in (ROOT / 'static' / 'js').glob('*.js') if p.name != 'icons.js'),
    *(ROOT / 'api').glob('*.py'),
]

RUNTIME = """\
/* Lucide v%(version)s (ISC license, https://lucide.dev) - only the icons this site uses.
   Generated by scripts/build_icons.py; do not edit by hand. */
(function () {
    'use strict';
    var NS = 'http://www.w3.org/2000/svg';
    var BASE = {xmlns: NS, width: 24, height: 24, viewBox: '0 0 24 24', fill: 'none',
        stroke: 'currentColor', 'stroke-width': 2, 'stroke-linecap': 'round', 'stroke-linejoin': 'round'};
    var ICONS = %(icons)s;

    function svg(tag, attrs, children) {
        var el = document.createElementNS(NS, tag);
        Object.keys(attrs).forEach(function (k) { el.setAttribute(k, String(attrs[k])); });
        (children || []).forEach(function (c) { el.appendChild(svg(c[0], c[1])); });
        return el;
    }

    function replace(el) {
        var name = el.getAttribute('data-lucide');
        var children = ICONS[name];
        if (!children) {
            console.warn(el.outerHTML + ' icon name was not found; run scripts/build_icons.py.');
            return;
        }
        var attrs = Object.assign({}, BASE, {'data-lucide': name});
        Array.prototype.forEach.call(el.attributes, function (a) { attrs[a.name] = a.value; });
        var classes = ['lucide', 'lucide-' + name].concat((el.getAttribute('class') || '').split(' '));
        attrs['class'] = classes.map(function (c) { return c.trim(); })
            .filter(function (c, i, all) { return c && all.indexOf(c) === i; }).join(' ');
        if (el.parentNode) el.parentNode.replaceChild(svg('svg', attrs, children), el);
    }

    window.lucide = {
        icons: ICONS,
        createIcons: function () {
            Array.prototype.forEach.call(document.querySelectorAll('[data-lucide]'), function (el) {
                if (el.namespaceURI !== NS) replace(el);
            });
        }
    };
})();
"""


def kebab_to_pascal(name):
    return re.sub(r'(\w)(\w*)(_|-|\s*)', lambda m: m.group(1).upper() + m.group(2).lower(), name)


def parse_lucide(source):
    """{PascalName: [[tag, {attrs}], ...]} for every icon and alias in the UMD build."""
    version = re.search(r'@license lucide v([\d.]+)', source).group(1)
    nodes = {}
    for m in re.finditer(r'const (\w+) = (?=\[\s*"svg",)', source):
        depth, i = 0, m.end()
        while True:  # find the matching close bracket; path data never contains brackets
            depth += {'[': 1, ']': -1}.get(source[i], 0)
            i += 1
            if depth == 0:
                break
        literal = source[m.end():i].replace('defaultAttributes', '{}')
        literal = re.sub(r'([{,]\s*)([A-Za-z_]\w*)\s*:', r'\1"\2":', literal)
        nodes[m.group(1)] = json.loads(literal)[2]
    aliases = re.search(r'var iconAndAliases = /\*#__PURE__\*/Object\.freeze\(\{(.*?)\}\);', source, re.S).group(1)
    names = {}
    for alias, const in re.findall(r'([A-Z]\w*): (\w+)', aliases):
        names[alias] = nodes[const]
    return version, names


def used_names(known):
    found = set()
    for path in SOURCES:
        text = path.read_text(encoding='utf-8')
        for s in re.findall(r'''["'`]([a-z][a-z0-9-]*)["'`]''', text):
            if kebab_to_pascal(s) in known:
                found.add(s)
    return sorted(found)


def main(lucide_js):
    version, known = parse_lucide(pathlib.Path(lucide_js).read_text(encoding='utf-8'))
    names = used_names(known)
    icons = {n: known[kebab_to_pascal(n)] for n in names}
    body = json.dumps(icons, separators=(',', ':'))
    OUT.write_text(RUNTIME % {'version': version, 'icons': body}, encoding='utf-8', newline='\n')
    print(f'{len(names)} icons, {OUT.stat().st_size // 1024} KB -> {OUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main(sys.argv[1])
